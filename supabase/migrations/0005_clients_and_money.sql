-- Clients, lead pipeline and manual money tracking (spec §7–8).
-- Money is a ledger: charges (what is owed), payments (what came in), allocations (which payment covers
-- which charge) and reversals (corrections). Ledger tables are append-only for users; balances are always
-- calculated, never stored. Amounts are integer minor units (cents) with a currency per amount.
-- This is internal tracking, not accounting, tax or payment collection.

-- ---------- clients ----------
create table public.clients (
  id uuid primary key default gen_random_uuid(),
  space_id uuid not null references public.spaces (id),
  name text not null check (length(trim(name)) > 0),
  contact_name text,
  email text,
  phone text,
  website text,
  location text,
  stage text not null default 'approached'
    check (stage in ('approached', 'discussion', 'proposal', 'client', 'paused', 'lost', 'archived')),
  responsible uuid references public.profiles (id),
  follow_up_on date,
  notes text,
  version int not null default 1,
  created_by uuid not null default auth.uid() references public.profiles (id),
  created_at timestamptz not null default now(),
  updated_by uuid references public.profiles (id),
  updated_at timestamptz not null default now()
);

create table public.client_versions (
  client_id uuid not null references public.clients (id) on delete cascade,
  version int not null,
  snapshot jsonb not null,
  actor uuid,
  recorded_at timestamptz not null default now(),
  primary key (client_id, version)
);

create function public.clients_guard() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if space_visibility(new.space_id) <> 'shared' then
    raise exception 'clients_live_in_shared_spaces' using errcode = '42501';
  end if;
  if tg_op = 'UPDATE' then
    if new.space_id <> old.space_id then
      raise exception 'client_space_fixed' using errcode = '42501';
    end if;
    new.id := old.id;
    new.created_by := old.created_by;
    new.created_at := old.created_at;
    new.version := old.version + 1;
    new.updated_by := auth.uid();
    new.updated_at := now();
  end if;
  return new;
end $$;
create trigger clients_guard before insert or update on public.clients for each row execute function public.clients_guard();

create function public.clients_snapshot() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into client_versions (client_id, version, snapshot, actor) values (new.id, new.version, to_jsonb(new), auth.uid());
  return new;
end $$;
create trigger clients_snapshot after insert or update on public.clients for each row execute function public.clients_snapshot();

create function public.can_access_client(p_client uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from clients c where c.id = p_client and can_access_space(c.space_id))
$$;

-- ---------- agreements (per-client snapshot of what was actually agreed) ----------
create table public.agreements (
  id uuid primary key default gen_random_uuid(),
  client_id uuid not null references public.clients (id),
  title text not null check (length(trim(title)) > 0),
  inclusions text,
  currency char(3) not null default 'ZAR' check (currency ~ '^[A-Z]{3}$'),
  price_minor bigint not null check (price_minor >= 0),
  deposit_minor bigint not null default 0 check (deposit_minor >= 0),
  billing text not null check (billing in ('once', 'monthly')),
  starts_on date not null,
  ends_on date,
  charge_day int not null check (charge_day between 1 and 31),
  created_by uuid default auth.uid() references public.profiles (id),
  created_at timestamptz not null default now(),
  op_id uuid unique,
  check (billing = 'monthly' or deposit_minor <= price_minor),
  check (ends_on is null or ends_on >= starts_on)
);

-- ---------- ledger ----------
create table public.charges (
  id uuid primary key default gen_random_uuid(),
  client_id uuid not null references public.clients (id),
  agreement_id uuid references public.agreements (id),
  description text not null check (length(trim(description)) > 0),
  amount_minor bigint not null check (amount_minor > 0),
  currency char(3) not null check (currency ~ '^[A-Z]{3}$'),
  due_on date not null,
  period_key text,
  created_by uuid default auth.uid() references public.profiles (id), -- null = generated by the schedule
  created_at timestamptz not null default now(),
  op_id uuid unique,
  unique (agreement_id, period_key)
);

create table public.payments (
  id uuid primary key default gen_random_uuid(),
  client_id uuid not null references public.clients (id),
  amount_minor bigint not null check (amount_minor > 0),
  currency char(3) not null check (currency ~ '^[A-Z]{3}$'),
  received_on date not null,
  method text,
  reference text,
  note text,
  recorded_by uuid not null default auth.uid() references public.profiles (id),
  recorded_at timestamptz not null default now(),
  op_id uuid not null unique
);

create table public.allocations (
  payment_id uuid not null references public.payments (id),
  charge_id uuid not null references public.charges (id),
  amount_minor bigint not null check (amount_minor > 0),
  primary key (payment_id, charge_id)
);

create table public.reversals (
  payment_id uuid primary key references public.payments (id),
  reason text not null check (length(trim(reason)) > 0),
  reversed_by uuid not null default auth.uid() references public.profiles (id),
  reversed_at timestamptz not null default now(),
  op_id uuid unique
);

-- An allocation must match client and currency, and may not over-fill the payment or the charge.
create function public.allocations_guard() returns trigger
language plpgsql security definer set search_path = public as $$
declare p payments; c charges; used_p bigint; used_c bigint;
begin
  select * into p from payments where id = new.payment_id for update;
  select * into c from charges where id = new.charge_id for update;
  if p.client_id <> c.client_id then
    raise exception 'allocation_client_mismatch' using errcode = '23514';
  end if;
  if p.currency <> c.currency then
    raise exception 'allocation_currency_mismatch' using errcode = '23514';
  end if;
  if exists (select 1 from reversals where payment_id = p.id) then
    raise exception 'payment_reversed' using errcode = '23514';
  end if;
  select coalesce(sum(amount_minor), 0) into used_p from allocations where payment_id = p.id;
  select coalesce(sum(a.amount_minor), 0) into used_c from allocations a
    where a.charge_id = c.id and not exists (select 1 from reversals r where r.payment_id = a.payment_id);
  if used_p + new.amount_minor > p.amount_minor then
    raise exception 'allocation_exceeds_payment' using errcode = '23514';
  end if;
  if used_c + new.amount_minor > c.amount_minor then
    raise exception 'allocation_exceeds_charge' using errcode = '23514';
  end if;
  return new;
end $$;
create trigger allocations_guard before insert on public.allocations for each row execute function public.allocations_guard();

-- ---------- calculated views (run as the caller, so RLS applies) ----------
create view public.charge_balances with (security_invoker = true) as
select c.id, c.client_id, c.agreement_id, c.description, c.amount_minor, c.currency, c.due_on, c.period_key,
       c.created_by, c.created_at,
       coalesce(sum(a.amount_minor) filter (where r.payment_id is null), 0)::bigint as paid_minor,
       (c.amount_minor - coalesce(sum(a.amount_minor) filter (where r.payment_id is null), 0))::bigint as outstanding_minor,
       case
         when c.amount_minor - coalesce(sum(a.amount_minor) filter (where r.payment_id is null), 0) = 0 then 'paid'
         when c.due_on < (now() at time zone 'Africa/Johannesburg')::date then 'overdue'
         else 'due'
       end as state
from charges c
left join allocations a on a.charge_id = c.id
left join reversals r on r.payment_id = a.payment_id
group by c.id;

-- One row per client per currency: amounts in different currencies are never added together.
create view public.client_balances with (security_invoker = true) as
select client_id, currency,
       sum(amount_minor)::bigint as charged_minor,
       sum(paid_minor)::bigint as paid_minor,
       sum(outstanding_minor)::bigint as outstanding_minor,
       coalesce(sum(outstanding_minor) filter (where state = 'overdue'), 0)::bigint as overdue_minor
from charge_balances
group by client_id, currency;

create view public.payment_ledger with (security_invoker = true) as
select p.*, (r.payment_id is not null) as reversed, r.reason as reversal_reason, r.reversed_by, r.reversed_at,
       coalesce((select sum(a.amount_minor) from allocations a where a.payment_id = p.id), 0)::bigint as allocated_minor
from payments p left join reversals r on r.payment_id = p.id;

-- ---------- actions (idempotent by op_id, so offline replays never double-post) ----------
create function public.add_charge(p_op_id uuid, p_client uuid, p_description text, p_amount_minor bigint,
                                  p_currency text, p_due_on date) returns uuid
language plpgsql set search_path = public as $$
declare v uuid;
begin
  select id into v from charges where op_id = p_op_id;
  if found then return v; end if;
  insert into charges (client_id, description, amount_minor, currency, due_on, op_id)
  values (p_client, p_description, p_amount_minor, upper(p_currency), p_due_on, p_op_id) returning id into v;
  return v;
end $$;

-- Allocates to the oldest outstanding charges in the same currency unless explicit allocations are given.
create function public.record_payment(p_op_id uuid, p_client uuid, p_amount_minor bigint, p_currency text,
                                      p_received_on date, p_method text default null, p_reference text default null,
                                      p_note text default null, p_allocations jsonb default null) returns jsonb
language plpgsql set search_path = public as $$
declare
  pay payments;
  remaining bigint;
  ch record;
  take bigint;
  a jsonb;
begin
  select * into pay from payments where op_id = p_op_id;
  if found then
    return jsonb_build_object('payment_id', pay.id, 'replayed', true,
      'allocated_minor', (select coalesce(sum(amount_minor), 0) from allocations where payment_id = pay.id));
  end if;
  insert into payments (client_id, amount_minor, currency, received_on, method, reference, note, op_id)
  values (p_client, p_amount_minor, upper(p_currency), p_received_on, p_method, p_reference, p_note, p_op_id)
  returning * into pay;
  remaining := pay.amount_minor;
  if p_allocations is null then
    for ch in select id, outstanding_minor from charge_balances
              where client_id = p_client and currency = pay.currency and outstanding_minor > 0
              order by due_on, created_at loop
      exit when remaining = 0;
      take := least(remaining, ch.outstanding_minor);
      insert into allocations (payment_id, charge_id, amount_minor) values (pay.id, ch.id, take);
      remaining := remaining - take;
    end loop;
  else
    for a in select * from jsonb_array_elements(p_allocations) loop
      insert into allocations (payment_id, charge_id, amount_minor)
      values (pay.id, (a->>'charge_id')::uuid, (a->>'amount_minor')::bigint);
      remaining := remaining - (a->>'amount_minor')::bigint;
    end loop;
  end if;
  return jsonb_build_object('payment_id', pay.id, 'replayed', false, 'allocated_minor', pay.amount_minor - remaining);
end $$;

create function public.reverse_payment(p_op_id uuid, p_payment uuid, p_reason text) returns text
language plpgsql set search_path = public as $$
begin
  if exists (select 1 from reversals where payment_id = p_payment) then
    return 'already_reversed';
  end if;
  insert into reversals (payment_id, reason, op_id) values (p_payment, p_reason, p_op_id);
  return 'reversed';
end $$;

-- Monthly obligations: one charge per calendar month with a stable period key (YYYY-MM).
-- Due day is clamped to the month's last day (31st -> 28/29 Feb). Re-running never duplicates.
create function public.ensure_monthly_charges(p_agreement uuid, p_through date) returns int
language plpgsql set search_path = public as $$
declare
  ag agreements;
  m date;
  due date;
  n int := 0;
begin
  select * into ag from agreements where id = p_agreement;
  if not found or ag.billing <> 'monthly' or ag.price_minor = 0 then return 0; end if;
  m := date_trunc('month', ag.starts_on)::date;
  while m <= p_through loop
    due := make_date(extract(year from m)::int, extract(month from m)::int,
                     least(ag.charge_day, extract(day from (m + interval '1 month - 1 day'))::int));
    if due >= ag.starts_on and due <= p_through and (ag.ends_on is null or due <= ag.ends_on) then
      insert into charges (client_id, agreement_id, description, amount_minor, currency, due_on, period_key, created_by)
      values (ag.client_id, ag.id, ag.title || ' — ' || to_char(m, 'FMMonth YYYY'), ag.price_minor, ag.currency, due,
              to_char(m, 'YYYY-MM'), auth.uid())
      on conflict (agreement_id, period_key) do nothing;
      if found then n := n + 1; end if;
    end if;
    m := (m + interval '1 month')::date;
  end loop;
  return n;
end $$;

create function public.create_agreement(p_op_id uuid, p_client uuid, p_title text, p_currency text,
                                        p_price_minor bigint, p_deposit_minor bigint, p_billing text,
                                        p_starts_on date, p_inclusions text default null,
                                        p_balance_due_on date default null) returns uuid
language plpgsql set search_path = public as $$
declare ag agreements;
begin
  select * into ag from agreements where op_id = p_op_id;
  if found then return ag.id; end if;
  insert into agreements (client_id, title, inclusions, currency, price_minor, deposit_minor, billing, starts_on, charge_day, op_id)
  values (p_client, p_title, p_inclusions, upper(p_currency), p_price_minor, coalesce(p_deposit_minor, 0), p_billing,
          p_starts_on, extract(day from p_starts_on)::int, p_op_id)
  returning * into ag;
  if ag.deposit_minor > 0 then
    insert into charges (client_id, agreement_id, description, amount_minor, currency, due_on, period_key)
    values (ag.client_id, ag.id, ag.title || ' — deposit', ag.deposit_minor, ag.currency, ag.starts_on, 'deposit');
  end if;
  if ag.billing = 'once' and ag.price_minor - ag.deposit_minor > 0 then
    insert into charges (client_id, agreement_id, description, amount_minor, currency, due_on, period_key)
    values (ag.client_id, ag.id, ag.title || ' — balance', ag.price_minor - ag.deposit_minor, ag.currency,
            coalesce(p_balance_due_on, ag.starts_on), 'balance');
  elsif ag.billing = 'monthly' then
    perform ensure_monthly_charges(ag.id, greatest(ag.starts_on, (now() at time zone 'Africa/Johannesburg')::date));
  end if;
  return ag.id;
end $$;

-- Ending an agreement stops future monthly charges; past charges and payments stay untouched.
create function public.end_agreement(p_agreement uuid, p_ends_on date) returns void
language plpgsql set search_path = public as $$
begin
  update agreements set ends_on = p_ends_on where id = p_agreement and ends_on is null;
  if not found then
    raise exception 'agreement_missing_or_already_ended' using errcode = 'P0002';
  end if;
end $$;

-- Daily job: create this month's charges for all running monthly agreements.
create function public.ensure_all_monthly_charges() returns int
language sql security definer set search_path = public as $$
  select coalesce(sum(ensure_monthly_charges(id, (now() at time zone 'Africa/Johannesburg')::date)), 0)::int
  from agreements where billing = 'monthly' and (ends_on is null or ends_on >= current_date - 31)
$$;

-- ---------- access ----------
alter table public.clients enable row level security;
alter table public.client_versions enable row level security;
alter table public.agreements enable row level security;
alter table public.charges enable row level security;
alter table public.payments enable row level security;
alter table public.allocations enable row level security;
alter table public.reversals enable row level security;

create policy clients_read on public.clients for select to authenticated using (can_access_space(space_id));
create policy clients_create on public.clients for insert to authenticated
  with check (created_by = auth.uid() and can_access_space(space_id));
create policy clients_edit on public.clients for update to authenticated
  using (can_access_space(space_id)) with check (can_access_space(space_id));
create policy client_versions_read on public.client_versions for select to authenticated using (can_access_client(client_id));

create policy agreements_read on public.agreements for select to authenticated using (can_access_client(client_id));
create policy agreements_create on public.agreements for insert to authenticated
  with check (created_by = auth.uid() and can_access_client(client_id));
create policy agreements_end on public.agreements for update to authenticated using (can_access_client(client_id));

create policy charges_read on public.charges for select to authenticated using (can_access_client(client_id));
create policy charges_create on public.charges for insert to authenticated
  with check (can_access_client(client_id) and (created_by = auth.uid() or created_by is null));
create policy payments_read on public.payments for select to authenticated using (can_access_client(client_id));
create policy payments_create on public.payments for insert to authenticated
  with check (recorded_by = auth.uid() and can_access_client(client_id));
create policy allocations_read on public.allocations for select to authenticated
  using (exists (select 1 from payments p where p.id = payment_id));
create policy allocations_create on public.allocations for insert to authenticated
  with check (exists (select 1 from payments p where p.id = payment_id and p.recorded_by = auth.uid()));
create policy reversals_read on public.reversals for select to authenticated
  using (exists (select 1 from payments p where p.id = payment_id));
create policy reversals_create on public.reversals for insert to authenticated
  with check (reversed_by = auth.uid() and exists (select 1 from payments p where p.id = payment_id));

grant select, insert, update on public.clients to authenticated;
grant select on public.client_versions to authenticated;
grant select, insert on public.agreements, public.charges, public.payments, public.allocations, public.reversals to authenticated;
grant update (ends_on) on public.agreements to authenticated; -- the only change allowed to an agreement
grant select on public.charge_balances, public.client_balances, public.payment_ledger to authenticated;
grant execute on function public.add_charge(uuid, uuid, text, bigint, text, date),
  public.record_payment(uuid, uuid, bigint, text, date, text, text, text, jsonb),
  public.reverse_payment(uuid, uuid, text), public.ensure_monthly_charges(uuid, date),
  public.create_agreement(uuid, uuid, text, text, bigint, bigint, text, date, text, date),
  public.end_agreement(uuid, date), public.can_access_client(uuid) to authenticated;
revoke execute on function public.ensure_all_monthly_charges() from public, anon, authenticated;
grant execute on function public.ensure_all_monthly_charges() to service_role;
grant all on public.clients, public.agreements, public.charges, public.payments, public.allocations, public.reversals to service_role;

-- Daily at 01:00 Johannesburg (23:00 UTC) on the hosted project; skipped where pg_cron is absent.
do $$
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    perform cron.unschedule(jobid) from cron.job where jobname = 'sidekick-monthly-charges';
    perform cron.schedule('sidekick-monthly-charges', '0 23 * * *', 'select public.ensure_all_monthly_charges()');
  end if;
end $$;
